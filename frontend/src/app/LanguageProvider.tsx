export type Language = keyof typeof translations
export type TranslationKey = keyof typeof translations.en

type LanguageContextValue = {
  language: Language
  setLanguage: (language: Language) => void
  translate: (key: TranslationKey) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

function getInitialLanguage(): Language {
  const savedLanguage = window.localStorage.getItem('lista-ni-lola-language')
  return savedLanguage === 'en' || savedLanguage === 'tl' ? savedLanguage : 'tl'
}

export function LanguageProvider({ children }: PropsWithChildren) {
  const [language, setLanguage] = useState<Language>(getInitialLanguage)

  useEffect(() => {
    window.localStorage.setItem('lista-ni-lola-language', language)
    document.documentElement.lang = language === 'tl' ? 'fil' : 'en'
  }, [language])

  const value: LanguageContextValue = {
    language,
    setLanguage,
    translate: (key) => translations[language][key],
  }

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)

  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider')
  }

  return context
}
